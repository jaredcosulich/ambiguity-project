// Fetch the Substack feed and write the snapshot the home Blog section reads.
//
//   npm run sync:substack
//
// The feed URL is `<substackUrl>/feed`, from settings.json. On any failure
// (network down, Substack erroring, unparseable feed) the existing snapshot is
// kept and a warning is logged — the deploy builds with the last good posts
// rather than failing. Run with tsx so it can share the tested parser in
// src/lib/substack.ts.
import * as fs from 'fs';
import * as path from 'path';
import { feedUrlFor, looksLikeRssFeed, parseSubstackFeed } from '../src/lib/substack.ts';
import { resolveDataRoot } from '../src/lib/contentRoot.ts';

const NOTE = 'Generated by scripts/sync-substack.mjs from the Substack feed — do not edit by hand. Edit posts in Substack.';

const dataRoot = resolveDataRoot();
const settings = JSON.parse(fs.readFileSync(path.join(dataRoot, 'settings.json'), 'utf-8'));
const outFile = path.join(dataRoot, 'substackPosts.json');

const keep = (reason) => {
  console.warn(`[sync-substack] ${reason} — keeping the existing ${path.relative(process.cwd(), outFile)}`);
  process.exit(0);
};

if (!settings.substackUrl) keep('no substackUrl in settings.json');

const feedUrl = feedUrlFor(settings.substackUrl);
let xml;
try {
  const res = await fetch(feedUrl, { signal: AbortSignal.timeout(20_000) });
  if (!res.ok) keep(`${feedUrl} returned HTTP ${res.status}`);
  xml = await res.text();
} catch (err) {
  keep(`could not fetch ${feedUrl}: ${err instanceof Error ? err.message : err}`);
}

if (!looksLikeRssFeed(xml)) keep(`${feedUrl} did not return an RSS feed`);

const posts = parseSubstackFeed(xml);
const snapshot = { _note: NOTE, feedUrl, syncedAt: new Date().toISOString(), posts };
fs.writeFileSync(outFile, `${JSON.stringify(snapshot, null, 2)}\n`);
console.log(`[sync-substack] wrote ${posts.length} post(s) from ${feedUrl}`);
